import { afterAll, beforeAll, expect, it, vi } from "vitest";
vi.mock("next/server", () => ({ connection: async () => {} }));
import { GET, POST } from "@/app/api/v1/projects/route";
import { PATCH, DELETE } from "@/app/api/v1/projects/[id]/route";
import { db } from "@/lib/server/db";
const owner = `test-projects-${crypto.randomUUID()}`;
const other = `${owner}-other`;
const req = (method: string, body?: unknown, origin?: string) => new Request("http://localhost/api/v1/projects", { method, headers: { host: "localhost", "Content-Type": "application/json", ...(origin ? { origin } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
const ctx = (id: string) => ({ params: Promise.resolve({ id }) });
const value = { name: "Weekly product", startDate: "2026-10-19", endDate: "2026-10-25", descriptionPoints: ["Build", "Ship"] };
beforeAll(() => {
  vi.stubEnv("DEV_USER_ID", owner);
  vi.stubEnv("APP_PIN_HASH", "");
  vi.stubEnv("SESSION_SECRET", "");
  vi.stubEnv("VERCEL_ENV", "");
});
afterAll(async () => {
  vi.unstubAllEnvs();
  await db.user.deleteMany({ where: { id: { in: [owner, other] } } });
  await db.$disconnect();
});
it("supports project CRUD, guards, unique weeks and owner isolation", async () => {
  expect((await POST(req("POST", value, "https://other.example"))).status).toBe(403);
  expect((await POST(req("POST", { ...value, endDate: "2026-10-27" }))).status).toBe(400);
  const created = await POST(req("POST", value));
  expect(created.status).toBe(201);
  const row = await created.json();
  expect(row.weekStart).toBe("2026-10-19");
  expect((await POST(req("POST", value))).status).toBe(409);
  expect((await (await GET(req("GET"))).json()).map((p: { id: string }) => p.id)).toContain(row.id);
  vi.stubEnv("DEV_USER_ID", other);
  expect(await (await GET(req("GET"))).json()).toEqual([]);
  expect((await PATCH(req("PATCH", { completed: true }), ctx(row.id))).status).toBe(404);
  expect((await DELETE(req("DELETE"), ctx(row.id))).status).toBe(404);
  expect((await POST(req("POST", value))).status).toBe(201);
  vi.stubEnv("DEV_USER_ID", owner);
  const second = await (await POST(req("POST", { ...value, startDate: "2026-10-26", endDate: "2026-11-01" }))).json();
  expect((await PATCH(req("PATCH", value), ctx(second.id))).status).toBe(409);
  expect((await (await PATCH(req("PATCH", { ...value, name: "Updated" }), ctx(row.id))).json()).name).toBe("Updated");
  const tick = (index: number, text: string, completed: boolean) => PATCH(req("PATCH", { pointIndex: index, pointText: text, completed }), ctx(row.id));
  const partial = await (await tick(0, "Build", true)).json();
  expect(partial.completedPoints).toEqual([true, false]);
  expect(partial.completedAt).toBeNull();
  const all = await (await tick(1, "Ship", true)).json();
  expect(all.completedPoints).toEqual([true, true]);
  expect(all.completedAt).toBeTruthy();
  expect((await (await tick(0, "Build", false)).json()).completedAt).toBeNull();
  expect((await tick(0, "Outdated text", true)).status).toBe(409);
  expect((await tick(10, "Build", true)).status).toBe(409);
  const reordered = await (await PATCH(req("PATCH", { ...value, descriptionPoints: ["Ship", "Build", "New"] }), ctx(row.id))).json();
  expect(reordered.completedPoints).toEqual([true, false, false]);
  expect(reordered.completedAt).toBeNull();
  expect((await (await PATCH(req("PATCH", { completed: true }), ctx(row.id))).json()).completedAt).toBeTruthy();
  expect((await (await PATCH(req("PATCH", { completed: false }), ctx(row.id))).json()).completedAt).toBeNull();
  expect((await DELETE(req("DELETE"), ctx(row.id))).status).toBe(204);
  expect((await DELETE(req("DELETE"), ctx(row.id))).status).toBe(404);
  vi.stubEnv("DEV_USER_ID", "");
  expect((await GET(req("GET"))).status).toBe(401);
});
